import React, { useEffect, useState } from "react";
import axios from "axios";
import { backendUrl } from "../App";

const EMPTY_FORM = {
  entity: "TSC",
  type: "manual_adjustment",
  title: "",
  description: "",
  expectedDate: new Date().toISOString().slice(0, 10),
  amount: 0,
  direction: "out",
  status: "forecast",
  source: "manual",
  notes: "",
};

const entities = ["TSC", "BMM", "Personal", "Savings", "Investment", "Crypto"];

const eventTypes = [
  "salary_out",
  "ni_out",
  "vat_out",
  "corporation_tax_out",
  "recurring_income",
  "recurring_expense",
  "manual_adjustment",
  "client_deposit_in",
  "client_balance_in",
  "supplier_payment_out",
];

const formatCurrency = (value = 0) =>
  new Intl.NumberFormat("en-GB", {
    style: "currency",
    currency: "GBP",
    maximumFractionDigits: 2,
  }).format(Number(value || 0));

const formatDate = (date) => {
  if (!date) return "-";
  return new Date(date).toLocaleDateString("en-GB", {
    day: "2-digit",
    month: "short",
    year: "numeric",
  });
};

const FinanceForecastEvents = () => {
  const [events, setEvents] = useState([]);
  const [form, setForm] = useState(EMPTY_FORM);
  const [editingId, setEditingId] = useState(null);
  const [entityFilter, setEntityFilter] = useState("TSC");
  const [statusFilter, setStatusFilter] = useState("forecast");
  const [loading, setLoading] = useState(false);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState("");

  const fetchEvents = async () => {
    try {
      setLoading(true);
      setError("");

      const params = {};
      if (entityFilter !== "ALL") params.entity = entityFilter;
      if (statusFilter !== "ALL") params.status = statusFilter;

      const res = await axios.get(`${backendUrl}/api/finance/forecast-events`, {
        params,
      });

      if (res.data?.success) {
        setEvents(res.data.forecastEvents || []);
      } else {
        setError(res.data?.message || "Could not load forecast events");
      }
    } catch (err) {
      console.error("fetch forecast events error:", err);
      setError(err.response?.data?.message || err.message);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchEvents();
  }, [entityFilter, statusFilter]);

  const resetForm = () => {
    setForm(EMPTY_FORM);
    setEditingId(null);
    setError("");
  };

  const handleChange = (e) => {
    const { name, value } = e.target;

    setForm((prev) => ({
      ...prev,
      [name]: name === "amount" ? Number(value) : value,
    }));
  };

  const handleEdit = (event) => {
    setEditingId(event._id);

    setForm({
      entity: event.entity || "TSC",
      type: event.type || "manual_adjustment",
      title: event.title || "",
      description: event.description || "",
      expectedDate: event.expectedDate
        ? new Date(event.expectedDate).toISOString().slice(0, 10)
        : new Date().toISOString().slice(0, 10),
      amount: Number(event.amount || 0),
      direction: event.direction || "out",
      status: event.status || "forecast",
      source: event.source || "manual",
      notes: event.notes || "",
    });
  };

  const handleSubmit = async (e) => {
    e.preventDefault();

    try {
      setSaving(true);
      setError("");

      if (!form.title.trim()) {
        setError("Title is required");
        return;
      }

      if (!form.expectedDate) {
        setError("Expected date is required");
        return;
      }

      if (Number(form.amount || 0) <= 0) {
        setError("Amount must be greater than 0");
        return;
      }

      const payload = {
        ...form,
        amount: Math.abs(Number(form.amount || 0)),
      };

      if (editingId) {
        await axios.put(
          `${backendUrl}/api/finance/forecast-events/${editingId}`,
          payload,
        );
      } else {
        await axios.post(`${backendUrl}/api/finance/forecast-events`, payload);
      }

      resetForm();
      await fetchEvents();
    } catch (err) {
      console.error("save forecast event error:", err);
      setError(err.response?.data?.message || err.message);
    } finally {
      setSaving(false);
    }
  };

  const handleDelete = async (event) => {
    if (event.isAutoGenerated) {
      setError(
        "Auto-generated forecast events should be changed from the booking, not deleted here.",
      );
      return;
    }

    const confirmed = window.confirm("Delete this manual forecast event?");
    if (!confirmed) return;

    try {
      setError("");
      await axios.delete(`${backendUrl}/api/finance/forecast-events/${event._id}`);
      await fetchEvents();
    } catch (err) {
      console.error("delete forecast event error:", err);
      setError(err.response?.data?.message || err.message);
    }
  };

  return (
    <div className="min-h-screen bg-gray-50 px-4 py-8 sm:px-8">
      <div className="mx-auto max-w-7xl">
        <div className="mb-6">
          <h1 className="text-2xl font-semibold text-gray-900">
            Forecast Events
          </h1>
          <p className="mt-1 text-sm text-gray-500">
            Add manual future cash movements like salary, tax, subscriptions and
            recurring expenses.
          </p>
        </div>

        {error && (
          <div className="mb-6 rounded-lg border border-red-200 bg-red-50 p-4 text-sm text-red-700">
            {error}
          </div>
        )}

        <div className="grid gap-6 lg:grid-cols-[420px_1fr]">
          <form
            onSubmit={handleSubmit}
            className="rounded-2xl bg-white p-5 shadow-sm"
          >
            <h2 className="mb-4 text-lg font-semibold text-gray-900">
              {editingId ? "Edit Forecast Event" : "Add Forecast Event"}
            </h2>

            <div className="space-y-4">
              <Input
                label="Title"
                name="title"
                value={form.title}
                onChange={handleChange}
                placeholder="Rhona salary"
              />

              <Input
                label="Description"
                name="description"
                value={form.description}
                onChange={handleChange}
                placeholder="Monthly salary"
              />

              <div className="grid grid-cols-2 gap-3">
                <Select
                  label="Entity"
                  name="entity"
                  value={form.entity}
                  onChange={handleChange}
                  options={entities}
                />

                <Select
                  label="Type"
                  name="type"
                  value={form.type}
                  onChange={handleChange}
                  options={eventTypes}
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <Input
                  label="Expected date"
                  name="expectedDate"
                  type="date"
                  value={form.expectedDate}
                  onChange={handleChange}
                />

                <Input
                  label="Amount"
                  name="amount"
                  type="number"
                  value={form.amount}
                  onChange={handleChange}
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <Select
                  label="Direction"
                  name="direction"
                  value={form.direction}
                  onChange={handleChange}
                  options={["in", "out"]}
                />

                <Select
                  label="Status"
                  name="status"
                  value={form.status}
                  onChange={handleChange}
                  options={["forecast", "confirmed", "paid", "cancelled", "ignored"]}
                />
              </div>

              <div>
                <label className="mb-1 block text-xs font-medium text-gray-600">
                  Notes
                </label>
                <textarea
                  name="notes"
                  value={form.notes}
                  onChange={handleChange}
                  rows="3"
                  className="w-full rounded-lg border border-gray-300 bg-white px-3 py-2 text-sm"
                />
              </div>

              <div className="flex gap-3">
                <button
                  type="submit"
                  disabled={saving}
                  className="rounded-lg bg-black px-4 py-2 text-sm font-medium text-white disabled:opacity-50"
                >
                  {saving
                    ? "Saving..."
                    : editingId
                      ? "Update Event"
                      : "Add Event"}
                </button>

                {editingId && (
                  <button
                    type="button"
                    onClick={resetForm}
                    className="rounded-lg border border-gray-300 bg-white px-4 py-2 text-sm font-medium text-gray-700"
                  >
                    Cancel
                  </button>
                )}
              </div>
            </div>
          </form>

          <div className="rounded-2xl bg-white p-5 shadow-sm">
            <div className="mb-4 flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between">
              <div>
                <h2 className="text-lg font-semibold text-gray-900">
                  Forecast Events
                </h2>
                <p className="text-sm text-gray-500">
                  Manual and booking-generated expected cash movements.
                </p>
              </div>

              <div className="flex gap-3">
                <Select
                  label="Entity"
                  value={entityFilter}
                  onChange={(e) => setEntityFilter(e.target.value)}
                  options={["ALL", ...entities]}
                />

                <Select
                  label="Status"
                  value={statusFilter}
                  onChange={(e) => setStatusFilter(e.target.value)}
                  options={["ALL", "forecast", "confirmed", "paid", "cancelled"]}
                />
              </div>
            </div>

            {loading ? (
              <div className="py-8 text-center text-sm text-gray-500">
                Loading forecast events...
              </div>
            ) : (
              <div className="overflow-x-auto">
                <table className="min-w-full text-left text-sm">
                  <thead>
                    <tr className="border-b text-xs uppercase tracking-wide text-gray-500">
                      <th className="px-3 py-3">Date</th>
                      <th className="px-3 py-3">Title</th>
                      <th className="px-3 py-3">Type</th>
                      <th className="px-3 py-3">Status</th>
                      <th className="px-3 py-3">Source</th>
                      <th className="px-3 py-3 text-right">Amount</th>
                      <th className="px-3 py-3 text-right">Actions</th>
                    </tr>
                  </thead>

                  <tbody>
                    {events.map((event) => (
                      <tr key={event._id} className="border-b last:border-0">
                        <td className="whitespace-nowrap px-3 py-3">
                          {formatDate(event.expectedDate)}
                        </td>
                        <td className="px-3 py-3">
                          <p className="font-medium text-gray-900">
                            {event.title}
                          </p>
                          <p className="text-xs text-gray-500">
                            {event.entity}
                          </p>
                        </td>
                        <td className="px-3 py-3 text-gray-500">
                          {event.type}
                        </td>
                        <td className="px-3 py-3">
                          <span className="rounded-full bg-gray-100 px-2 py-1 text-xs text-gray-700">
                            {event.status}
                          </span>
                        </td>
                        <td className="px-3 py-3 text-gray-500">
                          {event.isAutoGenerated ? "booking" : "manual"}
                        </td>
                        <td
                          className={`px-3 py-3 text-right font-medium ${
                            event.direction === "in"
                              ? "text-green-700"
                              : "text-red-700"
                          }`}
                        >
                          {event.direction === "out" ? "-" : "+"}
                          {formatCurrency(event.amount)}
                        </td>
                        <td className="px-3 py-3 text-right">
                          {!event.isAutoGenerated && (
                            <>
                              <button
                                onClick={() => handleEdit(event)}
                                className="mr-3 text-sm font-medium text-gray-700 underline"
                              >
                                Edit
                              </button>
                              <button
                                onClick={() => handleDelete(event)}
                                className="text-sm font-medium text-red-600 underline"
                              >
                                Delete
                              </button>
                            </>
                          )}

                          {event.isAutoGenerated && (
                            <span className="text-xs text-gray-400">
                              Auto-generated
                            </span>
                          )}
                        </td>
                      </tr>
                    ))}

                    {!events.length && (
                      <tr>
                        <td
                          colSpan="7"
                          className="px-3 py-8 text-center text-gray-500"
                        >
                          No forecast events found.
                        </td>
                      </tr>
                    )}
                  </tbody>
                </table>
              </div>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};

const Input = ({ label, name, value, onChange, type = "text", placeholder }) => (
  <div>
    <label className="mb-1 block text-xs font-medium text-gray-600">
      {label}
    </label>
    <input
      type={type}
      name={name}
      value={value}
      onChange={onChange}
      placeholder={placeholder}
      className="w-full rounded-lg border border-gray-300 bg-white px-3 py-2 text-sm"
    />
  </div>
);

const Select = ({ label, name, value, onChange, options }) => (
  <div>
    {label && (
      <label className="mb-1 block text-xs font-medium text-gray-600">
        {label}
      </label>
    )}
    <select
      name={name}
      value={value}
      onChange={onChange}
      className="w-full rounded-lg border border-gray-300 bg-white px-3 py-2 text-sm"
    >
      {options.map((option) => (
        <option key={option} value={option}>
          {option}
        </option>
      ))}
    </select>
  </div>
);

export default FinanceForecastEvents;